    public static XLWorkbook CreateDepartmentsWorkbook(IEnumerable<(string Name, string Description)>? departments = null)
    {
        var list = departments?.ToList() ?? DefaultCollegeDepartments.ToList();

        var workbook = new XLWorkbook();
        var worksheet = workbook.Worksheets.Add("أقسام الكلية (Departments)");
        worksheet.RightToLeft = true;

        // Header Styling
        var brandColor = XLColor.FromHtml("#21C87A");
        var darkHeaderColor = XLColor.FromHtml("#101828");

        worksheet.Cell(1, 1).Value = "م";
        worksheet.Cell(1, 2).Value = "اسم القسم (إلزامي)";
        worksheet.Cell(1, 3).Value = "الوصف والملاحظات (اختياري)";

        var headerRange = worksheet.Range(1, 1, 1, 3);
        headerRange.Style.Font.Bold = true;
        headerRange.Style.Font.FontSize = 12;
        headerRange.Style.Font.SetFontColor(XLColor.White);
        headerRange.Style.Fill.BackgroundColor = brandColor;
        headerRange.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
        headerRange.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
        worksheet.Row(1).Height = 28;

        int rowIdx = 2;
        for (int i = 0; i < list.Count; i++)
        {
            var item = list[i];
            worksheet.Cell(rowIdx, 1).Value = i + 1;
            worksheet.Cell(rowIdx, 2).Value = item.Name;
            worksheet.Cell(rowIdx, 3).Value = item.Description;

            worksheet.Cell(rowIdx, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
            worksheet.Cell(rowIdx, 2).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Right;
            worksheet.Cell(rowIdx, 3).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Right;

            if (rowIdx % 2 == 0)
            {
                worksheet.Range(rowIdx, 1, rowIdx, 3).Style.Fill.BackgroundColor = XLColor.FromHtml("#F7F9FC");
            }

            worksheet.Row(rowIdx).Height = 22;
            rowIdx++;
        }

        var dataRange = worksheet.Range(1, 1, rowIdx - 1, 3);
        dataRange.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
        dataRange.Style.Border.InsideBorder = XLBorderStyleValues.Thin;
        dataRange.Style.Border.OutsideBorderColor = XLColor.FromHtml("#D0D5DD");
        dataRange.Style.Border.InsideBorderColor = XLColor.FromHtml("#EAECF0");

        worksheet.Column(1).Width = 8;
        worksheet.Column(2).Width = 45;
        worksheet.Column(3).Width = 65;

        return workbook;
    }
